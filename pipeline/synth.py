"""Synthetic weather generator so the whole product runs with no network.

The output has the same columns as NASA POWER daily data and is written to
``raw/synth_<id>.csv``. Every file starts with a comment that says the values
are fake. Synthetic NDVI is written to ``raw/synth_ndvi_<id>.csv`` on the
36-dekad grid.

The generator deliberately produces false starts and late onsets so the onset
logic is exercised by real-looking data, not by a tidy curve.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

import numpy as np
import pandas as pd

try:
    from . import config
except ImportError:  # pragma: no cover - script mode
    import config

FAKE_HEADER = (
    "# SYNTHETIC DATA: generated by pipeline/synth.py for demonstration only.\n"
    "# These are fake values. Never present them as NASA observations.\n"
)


def _rng(location_id: str, year: int) -> np.random.Generator:
    material = f"{config.SYNTH_SEED}:{location_id}:{year}".encode("utf-8")
    seed = int.from_bytes(hashlib.sha256(material).digest()[:8], "big")
    return np.random.default_rng(seed)


def _location_offset(location_id: str) -> tuple[float, float, float]:
    """Small, stable per-location offsets for temperature, rain and greenness."""
    digest = hashlib.sha256(location_id.encode("utf-8")).digest()
    temp = (digest[0] / 255.0 - 0.5) * 1.6          # -0.8 .. +0.8 C
    rain = 0.85 + digest[1] / 255.0 * 0.35          # 0.85 .. 1.20
    green = (digest[2] / 255.0 - 0.5) * 0.08        # -0.04 .. +0.04 NDVI
    return temp, rain, green


def _season_peak(doy: np.ndarray) -> np.ndarray:
    """Wet-season shape: near zero in the dry months, peak in August."""
    return np.exp(-(((doy - 225.0) / 58.0) ** 2))


def _build_rain(year: int, dates: pd.DatetimeIndex, rng: np.random.Generator,
                rain_offset: float) -> tuple[np.ndarray, int, str]:
    """Return (daily rain, intended onset day-of-year, year character)."""
    doy = dates.dayofyear.to_numpy()
    n = len(dates)
    rain = np.zeros(n, dtype=float)

    onset = int(rng.integers(120, 156))  # 30 April - 4 June
    character = "normal"
    if year % 9 == 5:  # 2006, 2015, 2024: late seasons
        onset += int(rng.integers(24, 38))
        character = "late"
    if year % 7 == 3:  # 2003, 2010, 2017: false starts
        character = "false start"

    peak = _season_peak(doy)
    wet_probability = np.clip(0.05 + 0.55 * peak, 0.0, 0.72)
    wet_probability[doy < onset] = 0.0
    wet_probability[(doy > 310)] *= 0.25

    wet = rng.random(n) < wet_probability
    scale = 2.5 + 9.0 * peak
    amounts = rng.gamma(shape=1.6, scale=scale, size=n)
    rain[wet] = amounts[wet] * rain_offset

    # Guarantee a reliable start: 25 mm over three days, then no gap longer
    # than a few days through the sensitive first month.
    for index in range(onset - 1, min(onset + 2, n)):
        rain[index] = max(rain[index], (9.0, 8.0, 8.0)[index - (onset - 1)])
    for index in range(onset + 3, min(onset + 36, n)):
        recent = rain[max(0, index - 4):index]
        if float(recent.sum()) < 2.0:
            rain[index] = 6.0 + float(rng.random()) * 7.0

    # Occasional dry spells inside the season, but never close enough to the
    # onset to invalidate it.
    onset_index = onset - 1
    spells = 2 if rng.random() < 0.12 else (1 if rng.random() < 0.70 else 0)
    for _ in range(spells):
        start = onset_index + int(rng.integers(32, 110))
        length = int(rng.integers(5, 16))
        if start + length >= n:
            continue
        rain[start:start + length] = 0.0

    if character == "false start":
        burst = onset_index - int(rng.integers(22, 28))
        if burst >= 0:
            rain[burst:burst + 3] = [9.0, 8.0, 9.0]
            rain[burst + 3:onset_index] = 0.0  # the dry spell that rejects it

    return rain, onset, character


def generate_year(year: int, location_id: str) -> tuple[pd.DataFrame, pd.DataFrame, str]:
    """Generate one calendar year of daily weather and dekad NDVI."""
    dates = pd.date_range(f"{year}-01-01", f"{year}-12-31", freq="D")
    doy = dates.dayofyear.to_numpy()
    rng = _rng(location_id, year)
    temp_offset, rain_offset, green_offset = _location_offset(location_id)

    rain, intended_onset, character = _build_rain(year, dates, rng, rain_offset)

    seasonal = 33.2 + 5.6 * np.cos(2 * np.pi * (doy - 110) / 365.25)
    tmax = seasonal + temp_offset + rng.normal(0.0, 1.0, len(dates))

    soil = np.empty(len(dates))
    wetness = 0.18
    for index in range(len(dates)):
        wetness = 0.90 * wetness + 0.025 * float(rain[index])
        soil[index] = min(0.95, max(0.10, 0.15 + 0.90 * wetness))
    tmin = tmax - (10.0 + 4.0 * soil) + rng.normal(0.0, 0.7, len(dates))

    daily = pd.DataFrame({
        "T2M_MAX": np.round(tmax, 2),
        "T2M_MIN": np.round(tmin, 2),
        "PRECTOTCORR": np.round(rain, 2),
        "GWETROOT": np.round(soil, 3),
    }, index=dates)
    daily.index.name = "date"

    green = 0.10 + 0.62 * soil * np.clip(
        0.35 + 0.65 * np.exp(-(((doy - 245.0) / 95.0) ** 2)), 0.0, 1.0
    )
    green = np.clip(green + green_offset + rng.normal(0.0, 0.012, len(dates)), 0.05, 0.92)
    green_series = pd.Series(green, index=dates)
    blocks = np.minimum((dates.day.to_numpy() - 1) // 10, 2)
    grouped = green_series.groupby([dates.month, blocks])
    ndvi_rows = []
    for (month, block), values in grouped:
        day = (5, 15, 25)[int(block)]
        ndvi_rows.append({
            "date": pd.Timestamp(year=year, month=int(month), day=day),
            "ndvi": round(float(values.mean()), 3),
        })
    ndvi = pd.DataFrame(ndvi_rows).sort_values("date").reset_index(drop=True)

    daily.attrs["character"] = character
    daily.attrs["intended_onset"] = intended_onset
    return daily, ndvi, character


def write_location(location_id: str, raw_dir: Path | None = None) -> dict:
    """Write both synthetic files for one location. Returns a small summary."""
    raw = Path(raw_dir or config.RAW_DIR)
    raw.mkdir(parents=True, exist_ok=True)

    frames = []
    ndvi_frames = []
    characters = {}
    for year in config.data_years():
        daily, ndvi, character = generate_year(year, location_id)
        frames.append(daily)
        ndvi_frames.append(ndvi)
        characters[str(year)] = character

    daily = pd.concat(frames).sort_index()
    ndvi = pd.concat(ndvi_frames).sort_values("date").reset_index(drop=True)

    daily_path = raw / f"synth_{location_id}.csv"
    with daily_path.open("w", encoding="utf-8", newline="") as handle:
        handle.write(FAKE_HEADER)
        daily.to_csv(handle)

    ndvi_path = raw / f"synth_ndvi_{location_id}.csv"
    with ndvi_path.open("w", encoding="utf-8", newline="") as handle:
        handle.write(FAKE_HEADER)
        ndvi.to_csv(handle, index=False)

    return {
        "rows": len(daily),
        "ndvi_rows": len(ndvi),
        "characters": characters,
    }


def generate_all(locations: list[dict], raw_dir: Path | None = None,
                 verbose: bool = False) -> dict:
    summaries = {}
    for entry in locations:
        summary = write_location(entry["id"], raw_dir)
        summaries[entry["id"]] = summary
        if verbose:
            late = sum(1 for value in summary["characters"].values() if value == "late")
            false = sum(1 for value in summary["characters"].values() if value == "false start")
            print(f'    {entry["name"]:<14} {summary["rows"]} days, '
                  f'{late} late onsets, {false} false starts')
    return summaries


def load_daily(location_id: str, raw_dir: Path | None = None) -> pd.DataFrame:
    raw = Path(raw_dir or config.RAW_DIR)
    path = raw / f"synth_{location_id}.csv"
    frame = pd.read_csv(path, comment="#", parse_dates=["date"], index_col="date")
    return frame.sort_index()


def load_ndvi(location_id: str, raw_dir: Path | None = None) -> pd.DataFrame:
    raw = Path(raw_dir or config.RAW_DIR)
    path = raw / f"synth_ndvi_{location_id}.csv"
    frame = pd.read_csv(path, comment="#", parse_dates=["date"])
    return frame.sort_values("date").reset_index(drop=True)


def main() -> int:
    from . import locations  # local import keeps the module importable alone

    entries = locations.load_locations(verbose=True)
    print("Generating synthetic weather (fake data, labelled in every file):")
    generate_all(entries, verbose=True)
    print("Done.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
