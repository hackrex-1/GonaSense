"""Write the five frozen JSON contracts into ``web/data/``.

The computation lives in ``run_all.py``; this module owns the export shapes so
they can be checked in one place. Crops, strategies and glossary are
research-owned source files: they are read and validated, never overwritten.
"""

from __future__ import annotations

import json
from pathlib import Path

try:
    from . import config, locations
except ImportError:  # pragma: no cover - script mode
    import config
    import locations


def read_json(name: str, data_dir: Path | None = None):
    path = Path(data_dir or config.DATA_DIR) / name
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def write_json(name: str, payload, data_dir: Path | None = None) -> Path:
    directory = Path(data_dir or config.DATA_DIR)
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / name
    with path.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, ensure_ascii=False, allow_nan=False,
                  separators=(",", ":"))
        handle.write("\n")
    return path


def synthetic_sources() -> list[str]:
    return [
        "Synthetic daily weather generated by pipeline/synth.py "
        "(demo stand-in for NASA POWER)",
        "Synthetic NDVI on the 36-dekad grid (demo stand-in for MODIS MOD13Q1)",
    ]


def nasa_sources(has_imerg: bool = False, has_ndvi: bool = False) -> list[str]:
    sources = [
        "NASA POWER daily point API: T2M_MAX, T2M_MIN, PRECTOTCORR, GWETROOT "
        f"({config.YEARS[0]}-{config.YEARS[1]})"
    ]
    if has_imerg:
        sources.append("GPM IMERG Final daily precipitation (cross-check and confidence label)")
    if has_ndvi:
        sources.append("MODIS MOD13Q1 NDVI exported from NASA AppEEARS")
    return sources


def build_document(results: dict, data_mode: str,
                   sources_used: list[str] | None = None) -> dict:
    return {
        "data_mode": data_mode,
        "generated": config.today_iso(),
        "years": list(config.YEARS),
        "sources_used": sources_used or [],
        "locations": results,
    }


def write_locations(entries: list[dict] | None = None,
                    data_dir: Path | None = None) -> list[dict]:
    entries = entries or locations.load_locations()
    payload = [
        {
            "id": entry["id"],
            "name": entry["name"],
            "lat": entry["lat"],
            "lon": entry["lon"],
            "coords_status": entry["coords_status"],
        }
        for entry in entries
    ]
    write_json("locations.json", payload, data_dir)
    return payload


def write_metrics(results: dict, data_mode: str, sources_used: list[str] | None = None,
                  data_dir: Path | None = None) -> dict:
    document = build_document(results, data_mode, sources_used)
    write_json("metrics.json", document, data_dir)
    return document


def export_all(results: dict, data_mode: str, sources_used: list[str] | None = None,
               entries: list[dict] | None = None, data_dir: Path | None = None) -> dict:
    """Write locations.json and metrics.json; the other three files already exist."""
    for name in ("crops.json", "strategies.json", "glossary.json"):
        read_json(name, data_dir)  # fail early on a broken source file
    location_payload = write_locations(entries, data_dir)
    document = write_metrics(results, data_mode, sources_used, data_dir)
    document["location_count"] = len(location_payload)
    return document


def main(argv: list[str] | None = None) -> int:
    """CLI convenience: export by running the full pipeline."""
    from . import run_all

    return run_all.main(argv)


if __name__ == "__main__":
    raise SystemExit(main())
